var libmysql: ?std.DynLib = null;
//--------------------------------------------------------------------------------
pub fn init() !void {
    //------------------------------------------------------------
    libmysql = std.DynLib.open("libmysqlclient.so") catch std.DynLib.open("libmariadb.so") catch return error.LibraryNotFound;
    //------------------------------------------------------------
    var lib = libmysql orelse return error.LibraryNotOpen;
    //------------------------------------------------------------
    inline for (comptime @typeInfo(c).@"struct".decl_names) |decl_name| {
        //------------------------------------------------------------
        if (comptime !std.mem.startsWith(u8, decl_name, "mysql_")) continue;
        if (comptime @TypeOf(@field(c, decl_name)) == type) continue;
        const T = @TypeOf(@field(c, decl_name));
        @field(c, decl_name) =
            lib.lookup(T, decl_name) orelse return error.InvalidFunction;
        //------------------------------------------------------------
    }
    //------------------------------------------------------------
}
//--------------------------------------------------------------------------------
pub fn deinit() void {
    //------------------------------------------------------------
    if (libmysql != null) libmysql.?.close();
    //------------------------------------------------------------
}
