//------------------------------------------------------------
const std = @import("std");
//------------------------------------------------------------
const Parker = struct {
    //------------------------------------------------------------
    io: std.Io,
    mutex: std.Io.Mutex,
    condition: std.Io.Condition,
    permit: bool = false,
    //------------------------------------------------------------
    fn init(io: std.Io) Parker {
        return Parker{
            .io = io,
            .mutex = .init,
            .condition = .init,
            .permit = false,
        };
    }
    //-------------------------------------------------------
    pub fn park(self: *Parker) !void {
        //------------------------------------------------------------
        try self.mutex.lock(self.io);
        defer self.mutex.unlock(self.io);
        //------------------------------------------------------------
        while (!self.permit) {
            try self.condition.wait(self.io, &self.mutex);
        }
        //------------------------------------------------------------
        self.permit = false;
        //------------------------------------------------------------
    }
    //------------------------------------------------------------
    pub fn unpark(self: *Parker) !void {
        //------------------------------------------------------------
        try self.mutex.lock(self.io);
        defer self.mutex.unlock(self.io);
        //------------------------------------------------------------
        self.permit = true;
        //------------------------------------------------------------
        self.condition.signal(self.io);
        //------------------------------------------------------------
    }
    //------------------------------------------------------------
};
//------------------------------------------------------------
var parker: Parker = undefined;
var running = true;
//------------------------------------------------------------
var job_mutex: std.Io.Mutex = .init;
var job_available = false;
var job_value: i32 = 0;
//------------------------------------------------------------
fn worker(io: std.Io) !void {
    //------------------------------------------------------------
    while (running) {
        //------------------------------------------------------------
        try job_mutex.lock(io);
        //------------------------------------------------------------
        if (job_available) {
            const value = job_value;
            job_available = false;
            job_mutex.unlock(io);

            std.debug.print("worker processed {}\n", .{value});
        } else {
            job_mutex.unlock(io);

            std.debug.print("worker sleeping...\n", .{});

            try parker.park();

            std.debug.print("worker woke up\n", .{});
        }
        //------------------------------------------------------------
    }
    //------------------------------------------------------------
    std.debug.print("worker exiting\n", .{});
    //------------------------------------------------------------
}
//------------------------------------------------------------
fn submitJob(io: std.Io, value: i32) !void {
    //------------------------------------------------------------
    try job_mutex.lock(io);
    job_value = value;
    job_available = true;
    job_mutex.unlock(io);
    //------------------------------------------------------------
    try parker.unpark();
    //------------------------------------------------------------
}
//------------------------------------------------------------
pub fn main(init: std.process.Init) !void {
    //------------------------------------------------------------
    parker = Parker.init(init.io);
    const ms: usize = 200;
    //------------------------------------------------------------
    const t = try std.Thread.spawn(.{}, worker, .{init.io});
    //------------------------------------------------------------
    try init.io.sleep(.fromMilliseconds(ms), .real);
    //------------------------------------------------------------
    std.debug.print("submit 10\n", .{});
    try submitJob(init.io, 10);
    //------------------------------------------------------------
    try init.io.sleep(.fromMilliseconds(ms), .real);
    //------------------------------------------------------------
    std.debug.print("submit 20\n", .{});
    try submitJob(init.io, 20);
    //------------------------------------------------------------
    try init.io.sleep(.fromMilliseconds(ms), .real);
    //------------------------------------------------------------
    running = false;
    //------------------------------------------------------------
    try parker.unpark();
    //------------------------------------------------------------
    t.join();
    //------------------------------------------------------------
    std.debug.print("done\n", .{});
    //------------------------------------------------------------
}
