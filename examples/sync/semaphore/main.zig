//--------------------------------------------------------------------------------
const std = @import("std");
//--------------------------------------------------------------------------------
const LIMIT: usize = 2;
const TESTS: usize = 5;
//--------------------------------------------------------------------------------
pub const Context = struct {
    //--------------------------------------------------------------------------------
    io: std.Io,
    mutex: std.Io.Mutex,
    semaphore: std.Io.Semaphore,
    //--------------------------------------------------------------------------------
    pub fn init(io: std.Io) Context {
        return .{
            .io = io,
            .mutex = .init,
            .semaphore = .{ .permits = LIMIT },
        };
    }
    //--------------------------------------------------------------------------------
};
//--------------------------------------------------------------------------------
pub fn main(init: std.process.Init) !void {
    //------------------------------------------------------------
    var context = Context.init(init.io);
    //------------------------------------------------------------
    var threads: [TESTS]std.Thread = undefined;
    for (0..TESTS) |index| {
        threads[index] = try std.Thread.spawn(.{}, worker, .{ &context, index + 1 });
    }
    //------------------------------------------------------------
    for (0..TESTS) |index| {
        threads[index].join();
    }
    //------------------------------------------------------------
}
//--------------------------------------------------------------------------------
fn worker(context: *Context, id: usize) !void {
    //------------------------------------------------------------
    try context.semaphore.wait(context.io);
    //------------------------------------------------------------
    std.debug.print("worker {d} running\n", .{id});
    //------------------------------------------------------------
    try context.io.sleep(.fromSeconds(1), .real);
    //------------------------------------------------------------
    std.debug.print("worker {d} done\n", .{id});
    //------------------------------------------------------------
    context.semaphore.post(context.io);
    //------------------------------------------------------------
}
