//------------------------------------------------------------
const std = @import("std");
//------------------------------------------------------------
const TESTS: usize = 5;
//------------------------------------------------------------
var generation: usize = 0;
var done = false;
//------------------------------------------------------------
pub const Context = struct {
    io: std.Io,
    mutex: std.Io.Mutex,
    condition: std.Io.Condition,

    pub fn init(io: std.Io) Context {
        return .{
            .io = io,
            .mutex = .init,
            .condition = .init,
        };
    }
};
//------------------------------------------------------------
pub fn main(init: std.process.Init) !void {
    //------------------------------------------------------------
    std.debug.print("main started\n", .{});
    //------------------------------------------------------------
    var context = Context.init(init.io);
    //------------------------------------------------------------
    const t = try std.Thread.spawn(.{}, worker, .{&context});
    //------------------------------------------------------------
    for (0..TESTS) |_| {
        //------------------------------------------------------------
        try init.io.sleep(.fromMilliseconds(50), .real);
        //------------------------------------------------------------
        try context.mutex.lock(init.io);
        defer context.mutex.unlock(init.io);
        //------------------------------------------------------------
        generation += 1;
        //------------------------------------------------------------
        std.debug.print("main fired event {}\n", .{generation});
        //------------------------------------------------------------
        context.condition.broadcast(init.io);
        //------------------------------------------------------------
    }
    //------------------------------------------------------------
    try context.mutex.lock(init.io);
    done = true;
    context.condition.broadcast(init.io);
    context.mutex.unlock(init.io);
    //------------------------------------------------------------
    t.join();
    //------------------------------------------------------------
    std.debug.print("main ended\n", .{});
    //------------------------------------------------------------
}
//------------------------------------------------------------
fn worker(context: *Context) !void {
    //------------------------------------------------------------
    var last_generation: usize = 0;
    //------------------------------------------------------------
    while (true) {
        //------------------------------------------------------------
        try context.mutex.lock(context.io);
        //------------------------------------------------------------
        while (generation == last_generation and !done) {
            try context.condition.wait(context.io, &context.mutex);
        }
        //------------------------------------------------------------
        if (generation != last_generation) {
            //------------------------------------------------------------
            std.debug.print("worker received event {}\n", .{generation});
            //------------------------------------------------------------
            last_generation = generation;
            context.mutex.unlock(context.io);
            //------------------------------------------------------------
            continue;
            //------------------------------------------------------------
        }
        //------------------------------------------------------------
        if (done) {
            context.mutex.unlock(context.io);
            break;
        }
        //------------------------------------------------------------
        context.mutex.unlock(context.io);
        //------------------------------------------------------------
    }
    //------------------------------------------------------------
    std.debug.print("worker ended\n", .{});
    //------------------------------------------------------------
}
