//---------------------------------------------------------------------------
const std = @import("std");
//---------------------------------------------------------------------------
const WaitGroup = struct {
    //-------------------------------------------------------
    io: std.Io,
    members: std.atomic.Value(usize),
    //-------------------------------------------------------
    fn init(io: std.Io) WaitGroup {
        return .{
            .io = io,
            .members = std.atomic.Value(usize).init(0),
        };
    }
    //-------------------------------------------------------
    fn add(self: *WaitGroup) void {
        _ = self.members.fetchAdd(1, .acquire);
    }
    //-------------------------------------------------------
    fn done(self: *WaitGroup) void {
        _ = self.members.fetchSub(1, .release);
    }
    //-------------------------------------------------------
    fn wait(self: *const WaitGroup) !void {
        var backoff: i64 = 1;
        while (self.members.load(.monotonic) > 0) {
            try self.io.sleep(.fromMilliseconds(backoff), .real);
            backoff = @min(backoff * 2, 32);
        }
    }
    //-------------------------------------------------------
};
//---------------------------------------------------------------------------
fn worker(wg: *WaitGroup, id: usize) !void {
    //-------------------------------------------------------
    defer wg.done();
    std.debug.print("{} started\n", .{id});
    try wg.io.sleep(.fromMilliseconds(@as(i64, @intCast(id)) * 400), .real);
    std.debug.print("{} ended\n", .{id});
    //-------------------------------------------------------
}
//---------------------------------------------------------------------------
pub fn main(init: std.process.Init) !void {
    //-------------------------------------------------------
    var wg = WaitGroup.init(init.io);
    //-------------------------------------------------------
    for (1..6) |id| {
        //-------------------------------------------------------
        wg.add();
        //-------------------------------------------------------
        const thread = std.Thread.spawn(.{}, worker, .{ &wg, id }) catch |err| {
            wg.done();
            return err;
        };
        //-------------------------------------------------------
        thread.detach();
        //-------------------------------------------------------
    }
    //-------------------------------------------------------
    try wg.wait();
    //-------------------------------------------------------
}
