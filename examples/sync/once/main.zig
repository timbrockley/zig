//------------------------------------------------------------
const std = @import("std");
//------------------------------------------------------------
var once = Once{};
var value: i32 = 0;
//------------------------------------------------------------
const Once = struct {
    //--------------------------------------------------------------------------------
    // 0 = idle, 1 = running, 2 = done
    state: std.atomic.Value(u8) = std.atomic.Value(u8).init(0),
    //--------------------------------------------------------------------------------
    pub fn do(self: *Once, comptime init_fn: fn () void) void {
        //--------------------------------------------------------------------------------
        const state = self.state.load(.acquire);
        //--------------------------------------------------------------------------------
        if (state == 2) return;
        //--------------------------------------------------------------------------------
        if (state == 0 and self.state.cmpxchgStrong(0, 1, .acq_rel, .acquire) == null) {
            init_fn();
            self.state.store(2, .release);
            return;
        }
        //--------------------------------------------------------------------------------
        while (self.state.load(.acquire) != 2) {
            std.atomic.spinLoopHint();
        }
        //--------------------------------------------------------------------------------
    }
    //--------------------------------------------------------------------------------
};
//------------------------------------------------------------
fn initialize() void {
    //--------------------------------------------------------------------------------
    std.debug.print("initialising...\n", .{});
    value = 42;
    //--------------------------------------------------------------------------------
}
//------------------------------------------------------------
fn getValue() i32 {
    //--------------------------------------------------------------------------------
    once.do(initialize);
    return value;
    //--------------------------------------------------------------------------------
}
//------------------------------------------------------------
pub fn main() !void {
    //--------------------------------------------------------------------------------
    std.debug.print("{d}\n", .{getValue()});
    std.debug.print("{d}\n", .{getValue()});
    //--------------------------------------------------------------------------------
}
