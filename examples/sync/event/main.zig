//--------------------------------------------------------------------------------
const std = @import("std");
//--------------------------------------------------------------------------------
var event: std.Io.Event = .unset;
//--------------------------------------------------------------------------------
fn worker(io: std.Io) !void {
    //------------------------------------------------------------
    std.debug.print("worker is waiting\n", .{});
    try event.wait(io);
    std.debug.print("worker is running\n", .{});
    //------------------------------------------------------------
}
//--------------------------------------------------------------------------------
pub fn main(init: std.process.Init) !void {
    //------------------------------------------------------------
    std.debug.print("main is running\n", .{});
    //------------------------------------------------------------
    const t1 = try std.Thread.spawn(.{}, worker, .{init.io});
    defer t1.join();
    //------------------------------------------------------------
    event.set(init.io);
    //------------------------------------------------------------
}
