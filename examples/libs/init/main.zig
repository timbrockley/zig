//--------------------------------------------------------------------------------
const std = @import("std");
//--------------------------------------------------------------------------------
io: ?std.Io = null,
//------------------------------------------------------------
const Self = @This();
//------------------------------------------------------------
pub fn init(options: anytype) Self {
    //------------------------------------------------------------
    var self = Self{};
    //------------------------------------------------------------
    inline for (@typeInfo(@TypeOf(self)).@"struct".field_names) |field_name| {
        if (@hasField(@TypeOf(options), field_name)) {
            @field(self, field_name) = @field(options, field_name);
        }
    }
    //------------------------------------------------------------
    return self;
    //------------------------------------------------------------
}
//--------------------------------------------------------------------------------
pub fn unixTimestamp(self: *Self) !i64 {
    //------------------------------------------------------------
    return if (self.io) |io|
        std.Io.Timestamp.now(io, .real).toSeconds()
    else
        error.InvalidStdIo;
    //------------------------------------------------------------
}
//--------------------------------------------------------------------------------
pub fn main(minimal: std.process.Init.Minimal) !void {
    //------------------------------------------------------------
    var it = minimal.args.iterate();
    const name = if (it.next()) |arg0| std.fs.path.basename(arg0) else "";
    std.debug.print("{s}: main function\n", .{name});
    //------------------------------------------------------------
}
